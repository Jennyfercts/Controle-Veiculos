package br.dev.jenny.controle_veiculos;

/**
 *
 * @author sesi2dia
 */
public class Veiculo {
    String placa;
    String marca;
    String modelo;
    String motorista;
    int status;
    

    public Veiculo() {
    }

    public Veiculo(String placa, String marca, String modelo) {
        this.placa = placa;
        this.marca = marca;
        this.modelo = modelo;
        this.motorista = motorista;
        this.status = status;
    }
    
}
